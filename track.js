async function renderRecentArticles() {
  const grid = $('article-grid');
  if (!grid || grid.dataset.loaded) return;
  grid.dataset.loaded = 'true';
  try {
    const response = await fetch('/api/x-articles');
    if (!response.ok) throw new Error('Article feed unavailable');
    let feed = await response.json();
    if (feed.available === false) {
      const snapshot = await fetch('/data/x-articles.json');
      if (snapshot.ok) feed = await snapshot.json();
    }
    const {articles = []} = feed;
    if (!articles.length) {
      grid.innerHTML = '<p class="article-status">No recent linked articles found. New posts from @wo0tz0 will appear here automatically.</p>';
      return;
    }
    const escapeHtml = value => String(value).replace(/[&<>'"]/g, character => ({'&':'&amp;','<':'&lt;','>':'&gt;',"'":'&#39;','"':'&quot;'}[character]));
    grid.innerHTML = articles.map(article => `<a class="article-card" href="${escapeHtml(article.url)}" target="_blank" rel="noopener noreferrer"><span>${escapeHtml(article.date)}</span><h4>${escapeHtml(article.title)}</h4><p>${escapeHtml(article.source)}</p><b>Read article ↗</b></a>`).join('');
  } catch {
    grid.innerHTML = '<p class="article-status">Recent articles are temporarily unavailable. View @wo0tz0 on X ↗</p>';
  }
}

async function renderGithubActivity() {
  const heatmap = $('github-heatmap');
  if (!heatmap || heatmap.dataset.loaded) return;
  heatmap.dataset.loaded = 'true';

  try {
    const response = await fetch('https://github-contributions-api.jogruber.de/v4/notsomeonebutnoone?y=last');
    if (!response.ok) throw new Error('Contribution data unavailable');
    const {contributions = []} = await response.json();
    const byDate = new Map(contributions.map(day => [day.date, day]));
    const today = new Date();
    const start = new Date(today);
    start.setDate(today.getDate() - today.getDay() - (52 * 7));

    const weeks = Array.from({length: 53}, (_, week) => Array.from({length: 7}, (_, day) => {
      const date = new Date(start);
      date.setDate(start.getDate() + (week * 7) + day);
      const iso = date.toISOString().slice(0, 10);
      const activity = byDate.get(iso) || {count: 0, level: 0};
      return {...activity, date, iso};
    }));

    const monthLabels = weeks.map((week, index) => {
      const currentMonth = week[0].date.getMonth();
      const previousMonth = index ? weeks[index - 1][0].date.getMonth() : -1;
      return currentMonth !== previousMonth
        ? week[0].date.toLocaleDateString('en', {month: 'short'})
        : '';
    });

    heatmap.innerHTML = `<div class="github-months"><span></span>${monthLabels.map(month => `<span>${month}</span>`).join('')}</div><div class="github-chart"><div class="github-days"><span>Mon</span><span>Wed</span><span>Fri</span></div><div class="github-weeks">${weeks.map(week => `<div class="github-week">${week.map(day => `<span class="github-day" data-level="${Math.min(day.level || 0, 4)}" title="${day.count} contribution${day.count === 1 ? '' : 's'} on ${day.iso}"></span>`).join('')}</div>`).join('')}</div></div><div class="github-legend"><span>Less</span>${[0,1,2,3,4].map(level => `<i class="github-day" data-level="${level}"></i>`).join('')}<span>Many</span></div>`;
    const total = weeks.flat().reduce((sum, day) => sum + day.count, 0);
    heatmap.setAttribute('aria-label', `${total} GitHub contributions in the last year`);
  } catch {
    heatmap.innerHTML = '<span class="github-heatmap-status">Contribution activity available on GitHub ↗</span>';
    heatmap.removeAttribute('role');
  }
}

